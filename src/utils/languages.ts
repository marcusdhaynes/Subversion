export const ALL_LANGUAGES_SORTED: Language[] = [...ALL_LANGUAGES].sort((a, b) =>
  a.name.localeCompare(b.name)
);

export function getLanguageByCode(code?: string): Language {
  if (!code) return { code: 'en', name: 'English', nativeName: 'English' };
  const found = ALL_LANGUAGES.find((l) => l.code.toLowerCase() === code.toLowerCase());
  return found || { code, name: code.toUpperCase(), nativeName: code.toUpperCase() };
}

